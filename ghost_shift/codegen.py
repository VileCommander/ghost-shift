def slug() -> str:
    """Slug of the most recently chosen program (used for the filename)."""
    return _last_slug


# --------------------------------------------------------------------------
# persistent no-repeat state
# --------------------------------------------------------------------------
def _load_state() -> dict:
    try:
        return json.loads(STATE_PATH.read_text())
    except Exception:
        return {}


def _save_state(state: dict) -> None:
    try:
        STATE_PATH.parent.mkdir(parents=True, exist_ok=True)
        STATE_PATH.write_text(json.dumps(state))
    except Exception as exc:
        log(f"[!] could not save codegen state: {exc}")


def pick_task(state: dict, easy: bool = False) -> dict:
    if easy:
        pool = [t for t in TASKS if t["diff"] == 1 and t["slug"] != state.get("last")]
        return random.choice(pool or TASKS)
    bag = [s for s in state.get("bag", []) if s in BY_SLUG]
    if not bag:  # shuffle bag: show everything once before any repeat
        bag = list(BY_SLUG)
        random.shuffle(bag)
        if bag[0] == state.get("last"):
            bag.append(bag.pop(0))
    chosen = bag.pop(0)
    state["bag"] = bag
    state["last"] = chosen
    return BY_SLUG[chosen]


def pick_persona(state: dict) -> str:
    pool = [p for p in PERSONAS if p != state.get("persona")] or PERSONAS
    choice = random.choice(pool)
    state["persona"] = choice
    return choice


def pick_flavor(state: dict, n: int = 5) -> list:
    recent = state.get("flavor_recent", [])
    pool = [w for w in FLAVOR if w not in recent] or FLAVOR
    words = random.sample(pool, min(n, len(pool)))
    state["flavor_recent"] = (recent + words)[-30:]
    return words


# --------------------------------------------------------------------------
# prompt building
# --------------------------------------------------------------------------
def build_prompt(desc, hint, mode, iterations, delay, style, persona, words,
                 max_lines, modules) -> str:
    if mode == "frames":
        output_rule = (
            "- Animate by printing whole frames: print('\\033[2J', end='') once at the "
            "start, then at every step print('\\033[H' + frame_text)."
        )
    else:
        output_rule = (
            "- Print one line per step like a live log, and every so often print a "
            "small status summary."
        )
    return "\n".join([
        f"Write a complete Python 3 program: {desc}.",
        f"Approach: {hint}",
        "",
        "Rules:",
        f"- At most {max_lines} lines. Allowed imports: {', '.join(modules)}. "
        "No input(), no files, no network, no os, no sys.",
        output_rule,
        f"- Run for {iterations} steps with for step in range({iterations}) and "
        f"time.sleep({delay}) between steps, then print a one-line summary and stop.",
        f"- Look: {style}.",
        f"- Comments: short, in the voice of {persona}. Work a few of these words "
        f"in where natural: {', '.join(words)}.",
        "- Never use the words heap, buffer, allocate, neural or quantum.",
        "- Layout: constants first, small functions, then def main() and a call to "
        "main() at the bottom.",
        "- Output raw code only.",
    ])


def make_plan(state: dict, easy: bool, modules: list, max_lines: int) -> dict:
    task = pick_task(state, easy)
    desc = task["desc"]
    if task["variants"]:
        desc = desc.format(variant=random.choice(task["variants"]))
    if task["mode"] == "frames":
        delay = random.choice([0.08, 0.1, 0.12, 0.15, 0.2])
    else:
        delay = random.choice([0.4, 0.6, 0.8, 1.0])
    iterations = min(int(random.randint(45, 90) / delay), 700)
    persona = pick_persona(state)
    words = pick_flavor(state)
    prompt = build_prompt(desc, task["hint"], task["mode"], iterations, delay,
                          random.choice(STYLES), persona, words, max_lines, modules)
    return {"task": task, "prompt": prompt, "persona": persona, "words": words}


def scrub_comments(code: str, words: list) -> str:
    """Models still sneak banned words into comments; swap them for flavour."""
    out = []
    for line in code.splitlines():
        if line.lstrip().startswith("#"):
            line = re.sub(BANNED_WORDS, lambda m: random.choice(words), line,
                          flags=re.IGNORECASE)
        out.append(line)
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------
# public API used by the directors
# --------------------------------------------------------------------------
def generate_program(config: dict):
    """Return validated program source, or None if both attempts fail."""
    global _last_slug
    llm = config.get("llm", {})
    cg = config.get("codegen", {})
    model = llm.get("local_model", "qwen2.5-coder:3b")
    deadline = llm.get("deadline_s", 2400)
    modules = cg.get("allowed_modules", DEFAULT_MODULES)
    state = _load_state()

    # attempt 1: full-size task; attempt 2: an EASY task, smaller
    for easy, max_lines, max_tokens in ((False, 70, 1100), (True, 40, 650)):
        plan = make_plan(state, easy, modules, max_lines)
        task = plan["task"]
        log(f"[*] task={task['slug']} diff={task['diff']} model={model!r} "
            f"voice={plan['persona']!r} words={plan['words']}")
        try:
            raw = generate_local(
                plan["prompt"], model=model, system=SYSTEM_PROMPT,
                max_tokens=max_tokens, total_deadline=deadline, log=log,
            )
            _, _, cleaned = validate_code(strip_noise(raw))
            if cleaned and len(cleaned.strip()) >= 40:
                _last_slug = task["slug"]
                _save_state(state)
                return scrub_comments(cleaned, plan["words"])
            log("[!] generation produced too little code; trying an easier task")
        except Exception as exc:
            log(f"[!] generation attempt failed: {exc}")
    _save_state(state)
    return None


def fallback_program(workspace: Path):
    """Replay an archived program (new name, same code) or the static one."""
    global _last_slug
    archived = [p for p in workspace.glob("*_*.py") if p.stat().st_size > 200]
    if archived:
        pick = random.choice(archived)
        _last_slug = pick.stem.rsplit("_", 2)[0]
        return pick.read_text(), "archived"
    _last_slug = "sysmon"
    return FALLBACK_CODE, "static"


