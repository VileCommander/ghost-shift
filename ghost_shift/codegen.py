"""
ghost_shift/codegen.py
----------------------
Chooses WHAT the local model writes and builds the prompt.

Why this exists: with one fixed prompt (and a copyable example comment) a small
model writes the same program with the same comments every time. This module
adds variety from several independent sources:

  * ~28 distinct programs (Game of Life, Mandelbrot, maze solver, packet
    simulator, Markov babbler, Brainfuck interpreter, ...) at 3 difficulty
    levels, drawn from a persistent SHUFFLE BAG so nothing repeats until the
    whole catalogue has been shown.
  * Each task ships a one-sentence implementation hint, which makes hard tasks
    far more likely to succeed on a 3B model.
  * Random comment "voice" (persona), random vocabulary words to weave in,
    a banned-word list, random look, random run length and frame delay.
  * There are NO example comments in the prompt for the model to copy.
  * A retry after failure uses an EASY task instead of repeating the hard one.

Run `python -m ghost_shift.codegen` to print sample prompts without calling the
model.
"""

