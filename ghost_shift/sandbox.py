"""
ghost_shift/sandbox.py
----------------------
Validates generated Python code using AST (Abstract Syntax Trees) to ensure safety.
Automatically cleans markdown code wrappers (```python ... ```) generated by LLMs.
"""

import ast
import re
import logging

logger = logging.getLogger("ghost_shift.sandbox")

FORBIDDEN_NAMES = {"os", "sys", "subprocess", "shutil", "eval", "exec", "__import__"}

def clean_code_formatting(code_str: str) -> str:
    """
    Strips Markdown code block fences (```python ... ```) if present in the LLM output.
    """
    # Remove leading ```python or ``` tags
    code_str = re.sub(r"^```(?:python)?\n?", "", code_str.strip(), flags=re.IGNORECASE)
    # Remove trailing ``` tags
    code_str = re.sub(r"\n?```$", "", code_str.strip())
    return code_str.strip()

def validate_code(code_str: str):
    """
    Parses code into an AST and inspects imports to verify it contains no forbidden syntax.
    Returns (is_safe: bool, violations: list, cleaned_code: str).
    """
    # Strip markdown wrappers first!
    cleaned_code = clean_code_formatting(code_str)
    violations = []

    try:
        parsed = ast.parse(cleaned_code)
    except SyntaxError as e:
        logger.error(f"Syntax error during sandbox validation: {e}")
        return False, [f"Syntax Error: {e}"], cleaned_code

    for node in ast.walk(parsed):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name in FORBIDDEN_NAMES:
                    violations.append(f"Forbidden import: {alias.name}")
        elif isinstance(node, ast.ImportFrom):
            if node.module in FORBIDDEN_NAMES:
                violations.append(f"Forbidden import from: {node.module}")

    is_safe = len(violations) == 0
    return is_safe, violations, cleaned_code
